
CREATE TABLE STUDENTS (
    STUDENT_ID VARCHAR2(50) PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    BRANCH VARCHAR2(50) NOT NULL
);


CREATE TABLE PAPERS (
    PAPER_ID NUMBER PRIMARY KEY,
    TITLE VARCHAR2(255) NOT NULL,
    CATEGORY VARCHAR2(20) CHECK (CATEGORY IN ('Conference', 'Journal')),
    PUBLICATION_NAME VARCHAR2(255) NOT NULL,
    EVENT_DATE DATE NOT NULL,
    STATUS VARCHAR2(20) CHECK (STATUS IN ('Accepted', 'Presented', 'Published')),
    PROOF_LINK VARCHAR2(500),
    SEMESTER NUMBER NOT NULL,
    CONSTRAINT UNIQUE_PAPER UNIQUE (TITLE, PUBLICATION_NAME)
);


CREATE TABLE PAPER_AUTHORS (
    MAPPING_ID NUMBER PRIMARY KEY,
    PAPER_ID NUMBER REFERENCES PAPERS(PAPER_ID),
    STUDENT_ID VARCHAR2(50) REFERENCES STUDENTS(STUDENT_ID),
    AUTHOR_TYPE VARCHAR2(15) CHECK (AUTHOR_TYPE IN ('Student', 'Faculty', 'External')),
    CONTRIBUTION_PCT NUMBER(5,2)
);


CREATE TABLE GRACE_MARKS_SUMMARY (
    MARK_ID NUMBER PRIMARY KEY,
    STUDENT_ID VARCHAR2(50) REFERENCES STUDENTS(STUDENT_ID),
    PAPER_ID NUMBER REFERENCES PAPERS(PAPER_ID),
    MARKS_AWARDED NUMBER(5,2),
    SEMESTER NUMBER NOT NULL
);


