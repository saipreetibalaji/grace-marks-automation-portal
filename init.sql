SELECT s.NAME, p.TITLE, g.MARKS_AWARDED 
FROM GRACE_MARKS_SUMMARY g
JOIN STUDENTS s ON g.STUDENT_ID = s.STUDENT_ID
JOIN PAPERS p ON g.PAPER_ID = p.PAPER_ID;


SELECT 
    s.NAME as STUDENT_NAME, 
    p.TITLE as PAPER_TITLE, 
    pa.CONTRIBUTION_PCT as CONTRIBUTION, 
    g.MARKS_AWARDED as MARKS_PER_PAPER,
    SUM(g.MARKS_AWARDED) OVER (PARTITION BY s.STUDENT_ID) as TOTAL_STUDENT_GRACE_MARKS
FROM GRACE_MARKS_SUMMARY g
JOIN STUDENTS s ON g.STUDENT_ID = s.STUDENT_ID
JOIN PAPERS p ON g.PAPER_ID = p.PAPER_ID
JOIN PAPER_AUTHORS pa ON (pa.PAPER_ID = p.PAPER_ID AND pa.STUDENT_ID = s.STUDENT_ID)
ORDER BY s.NAME;


SELECT 
    s.BRANCH, 
    p.CATEGORY, 
    COUNT(DISTINCT p.PAPER_ID) as TOTAL_PAPERS
FROM PAPERS p
JOIN PAPER_AUTHORS pa ON p.PAPER_ID = pa.PAPER_ID
JOIN STUDENTS s ON pa.STUDENT_ID = s.STUDENT_ID
GROUP BY s.BRANCH, p.CATEGORY
ORDER BY s.BRANCH;


SELECT 
    NVL(s.BRANCH, 'GRAND TOTAL') as BRANCH, 
    NVL(s.NAME, '--- Branch Subtotal ---') as STUDENT_NAME, 
    SUM(g.MARKS_AWARDED) as TOTAL_MARKS
FROM GRACE_MARKS_SUMMARY g
JOIN STUDENTS s ON g.STUDENT_ID = s.STUDENT_ID
GROUP BY ROLLUP(s.BRANCH, s.NAME)
ORDER BY s.BRANCH;


